@app.post("/start_job", response_model=StartJobResponse)
async def start_job(payload: StartJobRequest):
    """MIP-003: Initiate a new job."""
    # Convert input_data array [{key, value}] to dict
    params = {}
    for item in payload.input_data:
        params[item.key] = item.value

    mode = params.get("mode", "verify_claim")
    if mode == "verify_claim" and not params.get("query") and not params.get("target_url"):
        raise HTTPException(status_code=400, detail="INVALID_INPUT: 'query' or 'target_url' required for verify_claim.")
    if mode == "read_web" and not params.get("target_url"):
        raise HTTPException(status_code=400, detail="INVALID_INPUT: 'target_url' required for read_web.")

    job_id = f"job-{uuid.uuid4().hex[:12]}"
    seller_id = f"seller-{job_id}"
    
    # In live testnet, blockchain_identifier and payment_address come from Masumi Payment Service
    # Here we mock standard Preprod testnet response until local Payment Service node is linked
    mock_blockchain_id = f"cardano-tx-{uuid.uuid4().hex[:16]}"
    mock_preprod_address = "addr_test1vrm0e7q3d98h6swr2juxk9c424sq7dflz2n4yqqc7n695ggu5g630"
    price_lovelace = 5_000_000  # 5 tADA (~100 credits)

    job_entry = {
        "job_id": job_id,
        "identifier_from_seller": seller_id,
        "identifier_from_purchaser": payload.identifier_from_purchaser,
        "blockchain_identifier": mock_blockchain_id,
        "payment_address": mock_preprod_address,
        "amount_lovelace": price_lovelace,
        "status": "awaiting_payment",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "mode": mode,
        "params": params
    }
    JOBS[job_id] = job_entry

    # For testing / demo without immediate payment hook: auto-trigger background worker
    # In live Masumi production, this trigger happens upon 'FundsLocked' event.
    asyncio.create_task(execute_job(job_id, mode, params, payload.identifier_from_purchaser))

    return StartJobResponse(
        job_id=job_id,
        identifier_from_seller=seller_id,
        blockchain_identifier=mock_blockchain_id,
        payment_address=mock_preprod_address,
        amount_lovelace=price_lovelace,
        status="awaiting_payment"
    )

@app.get("/status")
async def get_status(job_id: str = Query(..., description="Job ID returned by /start_job")):
    """MIP-003: Poll job status, results, and cryptographic hashes."""
    job = JOBS.get(job_id)
    if not job:
        raise HTTPException(status_code=404, detail="JOB_NOT_FOUND")

    status = job.get("status")

    if status == "awaiting_payment":
        return {
            "job_id": job_id,
            "status": "awaiting_payment",
            "payment_address": job["payment_address"],
            "amount_lovelace": job["amount_lovelace"]
        }
    elif status == "running":
        return {
            "job_id": job_id,
            "status": "running",
            "progress": job.get("progress", {"current_step": "In progress", "percentage": 50})
        }
    elif status == "completed":
        return {
            "job_id": job_id,
            "status": "completed",
            "output": job.get("output"),
            "input_hash": job.get("input_hash"),
            "output_hash": job.get("output_hash"),
            "decision_hash": job.get("decision_hash"),
            "execution_time_seconds": job.get("execution_time_seconds")
        }
    elif status == "failed":
        return {
            "job_id": job_id,
            "status": "failed",
            "error": job.get("error", "PROCESSING_ERROR"),
            "message": job.get("message", "Job processing failed.")
        }
    
    return {"job_id": job_id, "status": status}

