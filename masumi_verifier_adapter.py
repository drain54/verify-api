@app.get("/availability")
async def get_availability():
    """MIP-003: Health and operational load check."""
    uptime = int(time.time() - START_TIME)
    active = sum(1 for j in JOBS.values() if j.get("status") in ("awaiting_payment", "running"))
    return {
        "status": "available",
        "message": "AI Fact & Web Content Verifier ready",
        "uptime_seconds": uptime,
        "current_load": {
            "active_jobs": active,
            "queued_jobs": 0,
            "max_capacity": 50
        }
    }

