# Helper: RFC 8785 Canonical JSON & Decision Hash (MIP-004)
def canonical_dumps(data: Any) -> str:
    """Canonicalize JSON per RFC 8785 rules (sorted keys, compact separators)."""
    return json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False)

def compute_hashes(identifier_from_purchaser: str, input_data: Any, output_data: Any):
    canonical_input = canonical_dumps(input_data)
    canonical_output = canonical_dumps(output_data)
    
    in_str = f"{identifier_from_purchaser};{canonical_input}"
    out_str = f"{identifier_from_purchaser};{canonical_output}"
    
    in_hash = hashlib.sha256(in_str.encode("utf-8")).hexdigest()
    out_hash = hashlib.sha256(out_str.encode("utf-8")).hexdigest()
    decision_hash = in_hash + out_hash
    return in_hash, out_hash, decision_hash

# Background Task: Worker to execute job
async def execute_job(job_id: str, mode: str, params: Dict[str, Any], identifier_from_purchaser: str):
    job = JOBS.get(job_id)
    if not job:
        return

    job["status"] = "running"
    job["progress"] = {"current_step": "Processing request", "percentage": 30}
    t0 = time.time()

    try:
        output_result = {}
        if mode == "read_web":
            url = str(params.get("url") or params.get("target_url") or "")
            job["progress"] = {"current_step": f"Extracting {url}", "percentage": 60}
            res = await reader_backend.extract_url(
                url=url,
                include_links=bool(params.get("include_links", True)),
                include_images=bool(params.get("include_images", False))
            )
            output_result = res

        else: # verify_claim or probe
            query = params.get("query", "")
            req_type = params.get("type", "claim_verify")
            target_url = params.get("target_url")
            
            job["progress"] = {"current_step": "Analyzing claim & probing evidence", "percentage": 60}
            req = verify_engine.Req(
                query=query,
                type=req_type,
                depth=params.get("depth", "standard"),
                target_url=target_url
            )
            res = await verify_engine.verify(req)
            output_result = res

        elapsed = round(time.time() - t0, 2)
        in_hash, out_hash, dec_hash = compute_hashes(identifier_from_purchaser, params, output_result)

        job["status"] = "completed"
        job["output"] = output_result
        job["input_hash"] = in_hash
        job["output_hash"] = out_hash
        job["decision_hash"] = dec_hash
        job["execution_time_seconds"] = elapsed
        job["progress"] = {"current_step": "Done", "percentage": 100}

    except Exception as e:
        job["status"] = "failed"
        job["error"] = "PROCESSING_ERROR"
        job["message"] = str(e)[:300]
        job["execution_time_seconds"] = round(time.time() - t0, 2)


